async function fixCityData() {
  console.log('=== 修复城市数据 ===\n');

  await db.init();
  await new Promise(r => setTimeout(r, 500));

  try {
    // 1. 查找重复城市
    console.log('【1. 查找重复城市】');
    const duplicates = await db.query(`
      SELECT name, COUNT(*) as cnt, GROUP_CONCAT(id) as ids
      FROM cities
      WHERE list_type = 'china_general'
      GROUP BY name
      HAVING cnt > 1
      ORDER BY cnt DESC
    `);

    console.log(`发现 ${duplicates.length} 组重复城市\n`);

    // 2. 合并重复城市（保留有省份信息的，或第一条）
    console.log('【2. 合并重复城市】');
    let mergedCount = 0;

    for (const dup of duplicates) {
      const ids = dup.ids.split(',').map(Number);

      // 获取所有重复记录
      const cities = await db.query(`
        SELECT * FROM cities WHERE id IN (${ids.join(',')})
      `);

      // 找出最好的记录（有省份的优先）
      let bestCity = cities.find(c => c.province && c.province !== '-' && c.province.length > 1);
      if (!bestCity) bestCity = cities[0];

      // 删除其他重复记录
      const toDelete = ids.filter(id => id !== bestCity.id);
      for (const id of toDelete) {
        await db.run('DELETE FROM city_dimensions WHERE city_id = ?', [id]);
        await db.run('DELETE FROM city_tags WHERE city_id = ?', [id]);
        await db.run('DELETE FROM cities WHERE id = ?', [id]);
        mergedCount++;
      }

      console.log(`  ${dup.name}: 保留ID=${bestCity.id}, 删除${toDelete.length}条`);
    }
    console.log(`\n共删除 ${mergedCount} 条重复数据`);

    // 3. 补全省份信息
    console.log('\n【3. 补全省份信息】');
    const missingProvince = await db.query(`
      SELECT id, name, province FROM cities
      WHERE list_type = 'china_general'
        AND (province IS NULL OR province = '' OR province = '-')
    `);

    console.log(`发现 ${missingProvince.length} 个城市缺少省份信息`);

    let updatedCount = 0;
    for (const city of missingProvince) {
      // 尝试从映射表找省份
      let province = CITY_PROVINCE_MAP[city.name];

      // 如果没找到，尝试去掉"市"后缀
      if (!province) {
        const baseName = city.name.replace(/市$/, '');
        province = CITY_PROVINCE_MAP[baseName];
      }

      if (province) {
        await db.run('UPDATE cities SET province = ? WHERE id = ?', [province, city.id]);
        console.log(`  ${city.name} -> ${province}`);
        updatedCount++;
      }
    }
    console.log(`\n已更新 ${updatedCount} 个城市的省份信息`);

    // 4. 检查仍缺少省份的城市
    console.log('\n【4. 仍缺少省份的城市】');
    const stillMissing = await db.query(`
      SELECT name FROM cities
      WHERE list_type = 'china_general'
        AND (province IS NULL OR province = '' OR province = '-')
    `);

    if (stillMissing.length > 0) {
      console.log(`还有 ${stillMissing.length} 个城市需要手动补充:`);
      stillMissing.forEach(c => console.log(`  - ${c.name}`));
    } else {
      console.log('✓ 所有城市都有省份信息');
    }

    // 5. 统计结果
    console.log('\n【5. 修复后统计】');
    const stats = await db.query(`
      SELECT list_type, COUNT(*) as count
      FROM cities
      WHERE list_type IS NOT NULL
      GROUP BY list_type
    `);
    stats.forEach(s => {
      console.log(`  ${s.list_type}: ${s.count}个城市`);
    });

  } catch (error) {
    console.error('修复失败:', error);
  } finally {
    await db.close();
  }
}

fixCityData();
